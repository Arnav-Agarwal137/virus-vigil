// Builds src/wordscore.js: a word-count backup for detectProblem(), used only when no pattern matched.
// node tests/triage/build-wordscore.mjs
// Learns ONLY from the odd ("tune") rows of the blind sets; the even ("held") rows are never read here,
// so detect.mjs ... held stays an honest score. The confidence floor is chosen by leave-one-out over
// the same odd rows, never by looking at the held rows. 24 Sep 2026.
import fs from "node:fs";
import { tokens } from "../../src/wordscore-tokens.js";

const SETS = ["blind-1.json", "blind-2.json", "blind-3.json", "blind-4.json", "blind-5.json", "blind-6.json"];
const rows = [];
for (const f of SETS) {
  const all = JSON.parse(fs.readFileSync(new URL(f, import.meta.url), "utf8"));
  all.forEach((r, i) => { if (i % 2 === 1) rows.push([r[0], r[1]]); });
}

function train(rs) {
  const docs = {}, words = {}, totals = {}, vocab = new Set();
  for (const [fam, msg] of rs) {
    docs[fam] = (docs[fam] || 0) + 1;
    words[fam] ||= {};
    for (const w of new Set(tokens(msg))) {
      words[fam][w] = (words[fam][w] || 0) + 1;
      totals[fam] = (totals[fam] || 0) + 1;
      vocab.add(w);
    }
  }
  return { docs, words, totals, vocabSize: vocab.size, n: rs.length };
}

// Same scoring as src/wordscore.js (kept in step by the check at the bottom).
function score(m, msg) {
  const ws = tokens(msg).filter((w, i, a) => a.indexOf(w) === i);
  const logp = {};
  for (const fam of Object.keys(m.docs)) {
    let s = Math.log(m.docs[fam] / m.n);
    for (const w of ws) s += Math.log(((m.words[fam][w] || 0) + 1) / (m.totals[fam] + m.vocabSize));
    logp[fam] = s;
  }
  const max = Math.max(...Object.values(logp));
  let z = 0;
  for (const k in logp) z += Math.exp(logp[k] - max);
  const best = Object.keys(logp).reduce((a, b) => (logp[a] >= logp[b] ? a : b));
  return { fam: best, p: 1 / z };
}

// Leave-one-out over the tune rows: for each floor, how many rows would the backup get right / wrong?
// A backup that guesses wrong is worse than one that says nothing, so a wrong answer counts double.
const floors = [0.5, 0.6, 0.7, 0.8, 0.9, 0.95];
const loo = floors.map((fl) => ({ fl, right: 0, wrong: 0 }));
for (let i = 0; i < rows.length; i++) {
  const m = train(rows.filter((_, j) => j !== i));
  const g = score(m, rows[i][1]);
  for (const r of loo) {
    if (g.fam === "notproblem" || g.p < r.fl) continue;
    if (g.fam === rows[i][0]) r.right++; else r.wrong++;
  }
}
for (const r of loo) console.log(`floor ${r.fl}: ${r.right} right, ${r.wrong} wrong (net ${r.right - 2 * r.wrong})`);
const best = loo.reduce((a, b) => (b.right - 2 * b.wrong > a.right - 2 * a.wrong ? b : a));
console.log(`chosen floor ${best.fl} from ${rows.length} tune rows`);

const m = train(rows);
const out = `// GENERATED by tests/triage/build-wordscore.mjs from the odd (tune) rows of blind-1..5 - do not edit by hand.
// A backup for detectProblem(): only asked when no pattern matched. Rows: ${rows.length}. Floor chosen by leave-one-out.
import { tokens } from "./wordscore-tokens.js";
const M = ${JSON.stringify(m)};
export const WORD_FLOOR = ${best.fl};
// Every family with its probability, likeliest first; null when fewer than 2 words are known.
export function wordRank(msg) {
  const ws = tokens(msg).filter((w, i, a) => a.indexOf(w) === i);
  if (ws.filter((w) => Object.values(M.words).some((c) => c[w])).length < 2) return null;
  const logp = {};
  for (const fam of Object.keys(M.docs)) {
    let s = Math.log(M.docs[fam] / M.n);
    for (const w of ws) s += Math.log(((M.words[fam][w] || 0) + 1) / (M.totals[fam] + M.vocabSize));
    logp[fam] = s;
  }
  const max = Math.max(...Object.values(logp));
  let z = 0;
  for (const k in logp) z += Math.exp(logp[k] - max);
  return Object.keys(logp).map((fam) => ({ fam, p: Math.exp(logp[fam] - max) / z })).sort((a, b) => b.p - a.p);
}
export function wordGuess(msg) {
  const r = wordRank(msg);
  if (!r) return null;
  return r[0].fam === "notproblem" || r[0].p < WORD_FLOOR ? null : r[0].fam;
}
`;
fs.writeFileSync(new URL("../../src/wordscore.js", import.meta.url), out);
console.log(`wrote src/wordscore.js (${out.length} bytes)`);
