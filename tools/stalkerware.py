"""Build app/src/stalkerware.js from the Echap stalkerware-indicators list (CC-BY 4.0).

Pinned to one commit so the bundled list is reproducible:
    python tools/stalkerware.py            # from app/
Only package names, signing-certificate SHA-1s and names are kept (what a phone can compare
against its own installed apps). Every entry keeps its name; nothing is invented or merged.
"""
import csv
import io
import json
import re
import sys
import urllib.request

import yaml

COMMIT = "426156175adc84af7fbdd41486c046f9ecb40436"  # 20 Oct 2026, repo HEAD and latest touching ioc.yaml on 31 Oct 2026
URL = f"https://raw.githubusercontent.com/AssoEchap/stalkerware-indicators/{COMMIT}/ioc.yaml"
PKG = re.compile(r"^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)+$")
SHA1 = re.compile(r"^[0-9A-F]{40}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")


def main():
    raw = urllib.request.urlopen(URL, timeout=60).read().decode("utf-8")
    data = yaml.safe_load(raw)
    apps, bad = [], []
    for e in data:
        pk = sorted(set(e.get("packages") or []))
        certs = sorted({c.upper() for c in (e.get("certificates") or [])})
        bad += [p for p in pk if not PKG.match(p)] + [c for c in certs if not SHA1.match(c)]
        if not pk and not certs:
            continue  # website-only entries: nothing a phone can match
        apps.append({"name": e["name"], "packages": pk, "certs": certs})
    if bad:
        sys.exit(f"unexpected values in the list: {bad[:10]}")
    npk = sum(len(a["packages"]) for a in apps)
    nce = sum(len(a["certs"]) for a in apps)
    out = {
        "source": "https://github.com/AssoEchap/stalkerware-indicators",
        "commit": COMMIT,
        "license": "CC-BY 4.0, Echap (echap.eu.org) and contributors",
        "apps": apps,
    }
    js = ("// GENERATED by tools/stalkerware.py - do not edit by hand.\n"
          f"// Stalkerware indicators: {len(apps)} apps, {npk} package names, {nce} certificate SHA-1s.\n"
          f"// Source {out['source']} at {COMMIT[:12]}, licence {out['license']}.\n"
          "export const STALKERWARE = " + json.dumps(out, indent=0, ensure_ascii=True) + ";\n")
    with open("src/stalkerware.js", "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print(f"{len(data)} entries -> {len(apps)} matchable apps, {npk} packages, {nce} certs")

    # The same list for the Rust side (29 Sep 2026: app FILES in storage are checked too, not only
    # installed apps), plus samples.csv: the SHA-256 of every stalkerware APK Echap collected, which
    # the fingerprint look-up treats like a known-malware list entry. One line each, tab-separated:
    #   P <package> <app name> / C <cert sha1> <app name> / S <apk sha256> <app name>
    # build.rs stores it deflated (the package names are strings some pattern rules look for).
    raw_csv = urllib.request.urlopen(URL.replace("ioc.yaml", "samples.csv"), timeout=60).read().decode("utf-8")
    rows = list(csv.DictReader(io.StringIO(raw_csv)))
    lines = []
    for a in apps:
        name = a["name"].replace("\t", " ")
        lines += [f"P\t{p}\t{name}" for p in a["packages"]] + [f"C\t{c}\t{name}" for c in a["certs"]]
    shas = set()
    for r in rows:
        s = (r.get("SHA256") or "").strip().lower()
        if not SHA256.match(s):
            sys.exit(f"unexpected SHA256 in samples.csv: {s!r}")
        if s not in shas:
            shas.add(s)
            lines.append(f"S\t{s}\t{(r.get('App') or '?').strip().replace(chr(9), ' ')}")
    with open("src-tauri/data/stalkerware.tsv", "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# GENERATED by tools/stalkerware.py from {out['source']} at {COMMIT[:12]}, licence {out['license']}\n")
        f.write("\n".join(lines) + "\n")
    print(f"src-tauri/data/stalkerware.tsv: {len(shas)} sample fingerprints from {len(rows)} rows")


if __name__ == "__main__":
    main()
